use crate::ClientPlayState;

#[derive(Clone, Copy, Debug)]
pub struct SkyExtrapolationState {
    frozen: bool,
    time_of_day: u64,
    /// Time of the last change to the [`Self::time_of_day`] field.
    last_time_of_day_change_s: f64,
    /// The last result of calling [`Self::update`].
    last_update_result: f64,
}

impl Default for SkyExtrapolationState {
    fn default() -> Self {
        Self::new()
    }
}

impl SkyExtrapolationState {
    pub const fn new() -> Self {
        Self {
            frozen: true,
            time_of_day: 0,
            last_time_of_day_change_s: 0.0,
            last_update_result: 0.0,
        }
    }

    /// Returns the result from the last call to [`Self::update`].
    pub fn last_update_result(&self) -> f64 {
        self.last_update_result
    }

    /// Updates internal state, and returns a new extrapolated time of day for the current frame.
    pub fn update(&mut self, play_state: &ClientPlayState, current_time_s: f64) -> f64 {
        let world_time = &play_state.world_time;
        let ticking_state = &play_state.ticking_state;
        let new_frozen = world_time.sun_frozen || ticking_state.is_frozen;
        let old_frozen = core::mem::replace(&mut self.frozen, new_frozen);
        if world_time.time_of_day < self.time_of_day || new_frozen {
            // If we've jumped backwards in time, or we've just frozen, then we don't want to do
            // any smoothing at all.
            // Just jump to whatever the current frozen time is, whether it's changed or not.
            self.time_of_day = world_time.time_of_day;
            self.last_time_of_day_change_s = current_time_s;
            let time_of_day_f64 = world_time.time_of_day as f64;
            self.last_update_result = time_of_day_f64;
            return time_of_day_f64;
        }
        let extrapolation: f64 = if world_time.time_of_day > self.time_of_day || old_frozen {
            // If we've advanced the time of day, or we've just unfrozen, then just lock onto the
            // new time.
            self.time_of_day = world_time.time_of_day;
            self.last_time_of_day_change_s = current_time_s;
            world_time.time_of_day as f64
        } else {
            // Calculate extrapolation for this frame, using the ticking speed and the time since
            // the server last gave us a time update.
            let time_diff_s = current_time_s - self.last_time_of_day_change_s;
            let extrapolated_num_ticks: f64 = time_diff_s * ticking_state.ticks_per_second as f64;
            self.time_of_day as f64 + extrapolated_num_ticks
        };
        // Smooth out sky motion by interpolating between the last update result and the
        // extrapolated value.
        // TODO: Make this slightly less framerate-dependent.
        let extrapolation_diff = extrapolation - self.last_update_result;
        let interpolation = if extrapolation_diff.abs() <= 1.0 {
            // If we're within a tick, then it's close enough that we can just jump straight to it.
            // For the common case (framerate greater than tick rate), this means we're not
            // constantly slightly behind.
            extrapolation
        } else {
            // Otherwise, if this is a larger difference, then smooth out the motion so we don't
            // have see the time of day suddenly jumping.
            self.last_update_result + (extrapolation_diff * 0.5)
        };
        self.last_update_result = interpolation;
        interpolation
    }
}

pub fn get_rgb(time_of_day: f64) -> [f32; 3] {
    const DAY_RGB: [f32; 3] = [0.471, 0.655, 1.0];
    const NIGHT_RGB: [f32; 3] = [0.0, 0.0, 0.0];
    const DAY_NIGHT_RGB_DIFF: [f32; 3] = [
        DAY_RGB[0] - NIGHT_RGB[0],
        DAY_RGB[1] - NIGHT_RGB[1],
        DAY_RGB[2] - NIGHT_RGB[2],
    ];
    let light_level_percentage = get_light_level_percentage(time_of_day);
    [
        NIGHT_RGB[0] + (DAY_NIGHT_RGB_DIFF[0] * light_level_percentage),
        NIGHT_RGB[1] + (DAY_NIGHT_RGB_DIFF[1] * light_level_percentage),
        NIGHT_RGB[2] + (DAY_NIGHT_RGB_DIFF[2] * light_level_percentage),
    ]
}

/// Returns the Z axis rotation of the sky, in radians.
pub fn get_day_cycle_rotation(time_of_day: f64) -> f32 {
    ((time_of_day % 24000.0) as f32 / 24000.0) * core::f32::consts::TAU
}

/// Calculates the grey brightness that stars should be drawn at.
/// Stars should be rendered using additive blending, using an RGBA colour of
/// `[brightness, brightness, brightness, 0.0]`.
/// This means that if this returns zero, then stars are currently invisible.
pub fn get_star_brightness(time_of_day: f64) -> f32 {
    const MAX_BRIGHTNESS: f32 = 0.3;
    (1.0 - get_light_level_percentage(time_of_day)) * MAX_BRIGHTNESS
}

/// Calculates the current sky light level, between zero and one.
pub fn get_light_level_percentage(time_of_day: f64) -> f32 {
    let day_cycle_tick = time_of_day.round() as u64 % 24000;
    match day_cycle_tick {
        // Daytime.
        425..11576 => 1.0,
        // Turning night.
        11576..13219 => 1.0 - ((day_cycle_tick - 11576) as f32 / (13219 - 11576) as f32),
        // Night.
        13219..22782 => 0.0,
        // Turning day.
        22782..24000 | 0..425 => {
            let adjusted_tick = if (0_u64..425).contains(&day_cycle_tick) {
                day_cycle_tick + 24000
            } else {
                day_cycle_tick
            };
            (adjusted_tick - 22782) as f32 / (24425 - 22782) as f32
        }
        _ => unreachable!(),
    }
}

/// 3D star quads around a unit sphere.
pub static STAR_QUADS: [[[f32; 3]; 4]; 780] = {
    // FIXME: Figure out why these stars aren't in the correct position in the sky.
    let mut out: [[[f32; 3]; 4]; 780] = [[[0.0; 3]; 4]; 780];
    let mut i: usize = 0;
    while i < STARS.len() {
        let [ra, dec, rot, scale] = STARS[i];
        // Convert to spherical coordinates.
        let sph_inc = 90.0 - dec;
        let sph_azi = ra;
        // Create rotation matrices.
        #[rustfmt::skip]
        let rot_mat3 = {
            let sin = const_sin_degrees_approx(rot);
            let cos = const_cos_degrees_approx(rot);
            [
                [cos, 0.0, sin],
                [0.0, 1.0, 0.0],
                [-sin, 0.0, cos],
            ]
        };
        #[rustfmt::skip]
        let inc_mat3 = {
            let sin = const_sin_degrees_approx(-sph_inc);
            let cos = const_cos_degrees_approx(-sph_inc);
            [
                [1.0, 0.0, 0.0],
                [0.0, cos, -sin],
                [0.0, sin, cos],
            ]
        };
        #[rustfmt::skip]
        let azi_mat3 = {
            let sin = const_sin_degrees_approx(sph_azi);
            let cos = const_cos_degrees_approx(sph_azi);
            [
                [cos, 0.0, sin],
                [0.0, 1.0, 0.0],
                [-sin, 0.0, cos],
            ]
        };
        // Create base star quad.
        let base_quad = {
            // Create front-right quad corner, and normalise.
            let v = [scale, 100.0, scale];
            let recip_v_len = {
                let v_len_sqr = (v[0] * v[0]) + (v[1] * v[1]) + (v[2] * v[2]);
                // Approximate the square root using 5 rounds of Heron's formula.
                let v_len = v_len_sqr.max(1.0 / 4096.0) / 2.0;
                let v_len = 0.5 * (v_len + (v_len_sqr / v_len));
                let v_len = 0.5 * (v_len + (v_len_sqr / v_len));
                let v_len = 0.5 * (v_len + (v_len_sqr / v_len));
                let v_len = 0.5 * (v_len + (v_len_sqr / v_len));
                let v_len = 0.5 * (v_len + (v_len_sqr / v_len));
                v_len.recip()
            };
            let v = [v[0] * recip_v_len, v[1] * recip_v_len, v[2] * recip_v_len];
            // Create the full quad, centred around the origin.
            [
                [-v[0], v[1], -v[2]],
                [v[0], v[1], -v[2]],
                [v[0], v[1], v[2]],
                [-v[0], v[1], v[2]],
            ]
        };
        // Combine rotation matrices.
        let final_rot_mat3 = const_mat3_mul(azi_mat3, const_mat3_mul(inc_mat3, rot_mat3));
        // Rotate star quad into sky position.
        out[i] = [
            const_mat3_transform_point(final_rot_mat3, base_quad[0]),
            const_mat3_transform_point(final_rot_mat3, base_quad[1]),
            const_mat3_transform_point(final_rot_mat3, base_quad[2]),
            const_mat3_transform_point(final_rot_mat3, base_quad[3]),
        ];
        i += 1;
    }
    out
};

const fn const_mat3_transform_point(mat: [[f32; 3]; 3], pos: [f32; 3]) -> [f32; 3] {
    [
        (pos[0] * mat[0][0]) + (pos[1] * mat[0][1]) + (pos[2] * mat[0][2]),
        (pos[0] * mat[1][0]) + (pos[1] * mat[1][1]) + (pos[2] * mat[1][2]),
        (pos[0] * mat[2][0]) + (pos[1] * mat[2][1]) + (pos[2] * mat[2][2]),
    ]
}

const fn const_mat3_mul(a: [[f32; 3]; 3], b: [[f32; 3]; 3]) -> [[f32; 3]; 3] {
    let mut out: [[f32; 3]; 3] = [[0.0; 3]; 3];
    let mut y: usize = 0;
    while y < 3 {
        let mut x: usize = 0;
        while x < 3 {
            let a_row = a[y];
            let b_col = [b[0][x], b[1][x], b[2][x]];
            out[y][x] = (a_row[0] * b_col[0]) + (a_row[1] * b_col[1]) + (a_row[2] * b_col[2]);
            x += 1;
        }
        y += 1;
    }
    out
}

const fn const_sin_degrees_approx(mut x: f32) -> f32 {
    assert!(x.is_finite());
    while x < 0.0 {
        x += 360.0
    }
    while x > 360.0 {
        x -= 360.0;
    }
    let flip_result = x > 180.0;
    if flip_result {
        x -= 180.0;
    }
    let sin_approx = ((4.0 * x) * (180.0 - x)) / (40500.0 - (x * (180.0 - x)));
    if flip_result { -sin_approx } else { sin_approx }
}

const fn const_cos_degrees_approx(x: f32) -> f32 {
    const_sin_degrees_approx(x + 90.0)
}

